def get_svg_icon(name: str, color_hex: str | None = None, size: int = 24) -> QIcon:
    """Returns a QIcon generated from an inline SVG definition.
    If color_hex is provided (e.g. '#1DB954'), replaces 'currentColor' with it.
    """
    svg_text = SVG_DEFINITIONS.get(name)
    if not svg_text:
        return QIcon()

    if color_hex:
        svg_text = svg_text.replace("currentColor", color_hex)

    byte_array = QByteArray(svg_text.encode("utf-8"))
    renderer = QSvgRenderer(byte_array)

    pixmap = QPixmap(size, size)
    pixmap.fill(Qt.transparent)

    painter = QPainter(pixmap)
    renderer.render(painter)
    painter.end()

    return QIcon(pixmap)
